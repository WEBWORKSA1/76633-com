export function compatibility(a, b) {
  const x = reduce(a, false), y = reduce(b, false);
  let score = 55, label = 'Neutral — works with effort';
  if (NATURAL[x].includes(y)) { score = 88 + ((x * y) % 9); label = 'Natural match'; }
  else if (COMPAT[x].includes(y) || COMPAT[y].includes(x)) { score = 72 + ((x + y) % 8); label = 'Compatible'; }
  else if ((x + y) % 2 === 1 && Math.abs(x - y) > 4) { score = 40 + ((x + y) % 10); label = 'Challenging — growth match'; }
  return { score: Math.min(score, 97), label, x, y };
}

