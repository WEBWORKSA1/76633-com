export function pattern(s) {
  const u = new Set(s.split(''));
  if (s.length === 1) return { type: 'single', label: 'Root number' };
  if (u.size === 1) return { type: 'repeat', label: `Repeating ${s[0]}s — amplified ${D[+s[0]].name.toLowerCase()} energy` };
  const asc = s.split('').every((c, i) => i === 0 || +c === +s[i - 1] + 1);
  const desc = s.split('').every((c, i) => i === 0 || +c === +s[i - 1] - 1);
  if (asc) return { type: 'ascending', label: 'Ascending sequence — step-by-step progress' };
  if (desc) return { type: 'descending', label: 'Descending sequence — release & simplification' };
  if (s.length === 4 && s.slice(0, 2) === s.slice(2)) return { type: 'alternating', label: `Repeating pair ${s.slice(0, 2)} — a message on loop` };
  if (s === s.split('').reverse().join('')) return { type: 'mirror', label: 'Mirror (palindrome) number — reflection & alignment' };
  if (s.length === 4 && s[0] === s[1] && s[2] === s[3]) return { type: 'pairs', label: `Double pairs ${s[0]}${s[0]} + ${s[2]}${s[2]} — two themes working together` };
  return { type: 'mixed', label: 'Combination number — a blended message' };
}

