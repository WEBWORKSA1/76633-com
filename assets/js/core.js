export function relatedNumbers(s) {
  const out = new Set();
  const d = s[0];
  [d, d + d, d + d + d, d + d + d + d].forEach((x) => out.add(x));
  const r = String(reduce(digitSum(s), false));
  [r + r + r, r + r + r + r].forEach((x) => out.add(x));
  ['111', '222', '333', '444', '555', '777', '1111', '1212'].forEach((x) => out.add(x));
  out.delete(s);
  return [...out].slice(0, 10);
}

